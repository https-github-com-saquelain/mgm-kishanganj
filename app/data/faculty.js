// Helper to parse "Dr. X - Role" strings into { name, role } objects.
// Keeps the data section readable.
const p = (entries) =>
  entries.map((line) => {
    const idx = line.lastIndexOf(' - ')
    if (idx === -1) return { name: line.trim(), role: '' }
    return {
      name: line.slice(0, idx).trim(),
      role: line.slice(idx + 3).trim(),
    }
  })

